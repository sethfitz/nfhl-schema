"""The generator is a function of the snapshot."""

from __future__ import annotations

from pathlib import Path

import pytest

from nfhl import codegen
from nfhl.codegen import MODELS_DIR, generate
from nfhl.spec_source import Layer, SpecReader


def test_regenerating_from_the_snapshot_changes_nothing(tmp_path: Path) -> None:
    out = tmp_path / "models"
    generate(out)
    fresh = {p.name: p.read_text() for p in out.glob("*.py")}
    committed = {p.name: p.read_text() for p in MODELS_DIR.glob("*.py")}
    assert fresh.keys() == committed.keys()
    for name in fresh:
        assert fresh[name] == committed[name], f"{name} is stale; run generate-models"


def test_the_committed_models_are_marked_generated() -> None:
    for path in MODELS_DIR.glob("*.py"):
        assert "GENERATED by `scripts/generate-models`" in path.read_text(), path


def snapshot_of(directory: Path) -> dict[str, bytes]:
    return {p.name: p.read_bytes() for p in directory.iterdir()}


def test_a_failed_render_leaves_the_existing_models_untouched(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    out = tmp_path / "models"
    out.mkdir()
    (out / "kept.py").write_text("kept = True\n")
    before = snapshot_of(out)
    real_render_model = codegen.render_model
    rendered: list[Layer] = []

    def fail_on_the_third_model(layer: Layer, reader: SpecReader) -> str:
        if len(rendered) == 2:
            raise RuntimeError("render failed")
        rendered.append(layer)
        return real_render_model(layer, reader)

    monkeypatch.setattr(codegen, "render_model", fail_on_the_third_model)
    with pytest.raises(RuntimeError, match="render failed"):
        generate(out)
    assert len(rendered) == 2, "the failure came before every model rendered"
    assert snapshot_of(out) == before
    assert [p.name for p in tmp_path.iterdir()] == ["models"], "a temp dir was left"


def test_a_successful_render_replaces_the_existing_models(tmp_path: Path) -> None:
    out = tmp_path / "models"
    out.mkdir()
    (out / "kept.py").write_text("kept = True\n")
    written = generate(out)
    assert not (out / "kept.py").exists()
    assert snapshot_of(out).keys() == {p.name for p in written}
    assert all(p.parent == out for p in written)
    assert [p.name for p in tmp_path.iterdir()] == ["models"]
